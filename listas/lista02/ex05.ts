const numeroMaiorMenor: number = Number(prompt("digite um número"))
const numeroMenorMaior: number = Number(prompt("digite outro número"))

if(numeroMaiorMenor > numeroMenorMaior){
    alert(`O numero ${numeroMaiorMenor} é maior que o numero ${numeroMenorMaior}`)
} else if (numeroMenorMaior > numeroMaiorMenor){
    alert(`O numero ${numeroMenorMaior} é maior que o numero ${numeroMaiorMenor}`)
} else {
    alert(`Os dois números possuem o mesmo valor.`)
}